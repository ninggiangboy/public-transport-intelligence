// Writes src/api/generated/examples.ts from the response examples in backend/api/openapi.json, which are the DOC-32
// examples kept next to the controllers. Each example is checked with `satisfies` against the response type that
// openapi-typescript generated, so an example that drifts from its schema fails `tsc`. The MSW handlers of
// src/test/handlers.ts serve them. Run through `pnpm gen:api`.
import { readFileSync, writeFileSync } from 'node:fs';

const SPEC = new URL('../../backend/api/openapi.json', import.meta.url);
const OUT = new URL('../src/api/generated/examples.ts', import.meta.url);

const spec = JSON.parse(readFileSync(SPEC, 'utf8'));
const entries = [];
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, operation] of Object.entries(item)) {
    for (const [status, response] of Object.entries(operation.responses ?? {})) {
      if (!status.startsWith('2')) continue;
      const json = response.content?.['application/json'];
      if (!json?.examples) continue;
      const examples = Object.fromEntries(
        Object.entries(json.examples).map(([name, example]) => [name, example.value]),
      );
      entries.push({ operationId: operation.operationId, method, path, status: Number(status), examples });
    }
  }
}
entries.sort((a, b) => a.operationId.localeCompare(b.operationId));

const lines = [
  '// Generated by scripts/gen-api-examples.mjs from backend/api/openapi.json. Do not edit; run `pnpm gen:api`.',
  "import type { OperationExamples } from '../types';",
  '',
];
for (const { operationId, method, path, status, examples } of entries) {
  lines.push(
    `export const ${operationId} = {`,
    `  operationId: '${operationId}',`,
    `  method: '${method}',`,
    `  path: '${path}',`,
    `  status: ${status},`,
    `  examples: ${JSON.stringify(examples, null, 2).replaceAll('\n', '\n  ')},`,
    `} satisfies OperationExamples<'${path}', '${method}', ${status}>;`,
    '',
  );
}
lines.push(`export const allExamples = [${entries.map((e) => e.operationId).join(', ')}];`, '');
writeFileSync(OUT, lines.join('\n'));
console.log(`${entries.length} operations → ${OUT.pathname}`);
